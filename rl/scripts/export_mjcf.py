#!/usr/bin/env python3
"""Generate the training MJCF `humanoid_rl/assets/humanoid_rl.xml` from the shared description.

The model is built from `humanoid_description/urdf/humanoid.xacro` (via the `xacro` executable)
and converted with `humanoid_mujoco.model.urdf_to_mjcf`, so the kinematics, inertias, joint
limits, effort limits and damping are identical to the Gazebo and MuJoCo-ROS models. On top of
that the exporter adds what RL training needs:

* a free joint on `base`, a floor, a torso IMU site with gyro/accelerometer/orientation sensors,
  sole sites with position/velocity sensors and touch sensors,
* position actuators with the RL gains and armature from `humanoid_rl.constants`,
* collision filtering: only the feet collide (with the floor and with each other),
* MJX-friendly options (Newton solver with few iterations, pyramidal cone, no eulerdamp),
* a `home` keyframe with the standing pose and the feet resting on the floor.

Requires a sourced ROS 2 workspace (for `xacro` and `$(find humanoid_description)`):

    source /opt/ros/humble/setup.bash && source install/setup.bash
    python3 rl/scripts/export_mjcf.py
"""

import argparse
import os
import subprocess
import sys
import xml.etree.ElementTree as ET

import mujoco

RL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_DIR = os.path.dirname(RL_DIR)
sys.path.insert(0, RL_DIR)
sys.path.insert(0, os.path.join(REPO_DIR, 'src', 'humanoid_mujoco'))

from humanoid_mujoco.model import urdf_to_mjcf  # noqa: E402
from humanoid_rl import constants as c  # noqa: E402

XACRO_PATH = os.path.join(REPO_DIR, 'src', 'humanoid_description', 'urdf', 'humanoid.xacro')
SIM_DT = 0.004
FOOT_FRICTION = '1 0.005 0.0001'
# Collision bits: feet and floor share bit 1, every other robot geom has no collision bits.
COLLIDE = ('1', '1')
NO_COLLIDE = ('0', '0')
# Clearance between the lowest sole corner and the floor in the home keyframe [m].
HOME_CLEARANCE = 0.001

HEADER = (' GENERATED by rl/scripts/export_mjcf.py from humanoid_description; do not edit. '
          'Regenerate after changing the description or humanoid_rl/constants.py. ')


def expand_xacro(path: str) -> str:
    """Expand the description Xacro into a URDF string."""
    return subprocess.run(['xacro', path], check=True, capture_output=True, text=True).stdout


def _fmt(values) -> str:
    return ' '.join(f'{v:.6g}' for v in values)


def _add_world(root: ET.Element) -> None:
    root.insert(0, ET.Element('compiler', angle='radian', autolimits='true'))
    option = ET.Element('option', timestep=f'{SIM_DT:g}', iterations='4', ls_iterations='8',
                        solver='Newton', integrator='implicitfast', cone='pyramidal')
    ET.SubElement(option, 'flag', eulerdamp='disable')
    root.insert(1, option)
    default = ET.Element('default')
    ET.SubElement(default, 'geom', contype=NO_COLLIDE[0], conaffinity=NO_COLLIDE[1])
    root.insert(2, default)

    visual = ET.SubElement(root, 'visual')
    ET.SubElement(visual, 'headlight', ambient='0.4 0.4 0.4', diffuse='0.6 0.6 0.6',
                  specular='0 0 0')
    ET.SubElement(visual, 'global', azimuth='120', elevation='-20', offwidth='1280',
                  offheight='720')
    asset = ET.SubElement(root, 'asset')
    ET.SubElement(asset, 'texture', name='grid', type='2d', builtin='checker', width='512',
                  height='512', rgb1='0.2 0.3 0.4', rgb2='0.3 0.4 0.5')
    ET.SubElement(asset, 'material', name='grid', texture='grid', texrepeat='1 1',
                  texuniform='true', reflectance='0.1')

    worldbody = root.find('worldbody')
    worldbody.insert(0, ET.Element('light', name='sun', pos='0 0 10', dir='0 0 -1',
                                   directional='true'))
    worldbody.insert(1, ET.Element('geom', name=c.FLOOR_GEOM, type='plane', size='0 0 0.05',
                                   material='grid', contype=COLLIDE[0],
                                   conaffinity=COLLIDE[1], friction=FOOT_FRICTION))


def _add_robot(root: ET.Element) -> None:
    base = root.find(f"worldbody/body[@name='{c.BASE_BODY}']")
    if base is None:
        raise ValueError(f'Description has no root body named {c.BASE_BODY!r}')
    base.insert(0, ET.Element('freejoint', name=c.ROOT_JOINT))
    # Side camera tracking the robot: forward is +Y, so look along -X.
    base.insert(1, ET.Element('camera', name='track', mode='trackcom', pos='3 0 0.9',
                              xyaxes='0 1 0 -0.3 0 1'))

    for body in root.iter('body'):
        for index, geom in enumerate(body.findall('geom')):
            suffix = '' if index == 0 else f'_{index}'
            geom.set('name', f"{body.get('name')}_collision{suffix}")

    torso = root.find(f".//body[@name='{c.TORSO_BODY}']")
    ET.SubElement(torso, 'site', name=c.IMU_SITE, pos='0 0 0', size='0.01')

    sx, sy, sz = c.FOOT_SIZE
    ox, oy, oz = c.FOOT_OFFSET
    for body_name, geom_name, site in zip(c.FOOT_BODIES, c.FOOT_GEOMS, c.FOOT_SITES):
        foot = root.find(f".//body[@name='{body_name}']")
        geom = foot.find(f"geom[@name='{geom_name}']")
        if geom is None:
            raise ValueError(f'Foot body {body_name!r} has no geom {geom_name!r}')
        geom.set('contype', COLLIDE[0])
        geom.set('conaffinity', COLLIDE[1])
        geom.set('friction', FOOT_FRICTION)
        ET.SubElement(foot, 'site', name=site, pos=_fmt((ox, oy, oz - sz / 2)), size='0.01')
        # Touch volume around the sole: contact points lie within the penetration depth.
        ET.SubElement(foot, 'site', name=f'{site}_touch', type='box', group='4',
                      pos=_fmt((ox, oy, oz - sz / 2)),
                      size=_fmt((sx / 2 + 0.005, sy / 2 + 0.005, 0.02)))

    for joint in root.iter('joint'):
        joint.set('armature', f'{c.ARMATURE:g}')

    actuator = ET.SubElement(root, 'actuator')
    for name in c.JOINT_NAMES:
        leg_joint = name.split('_', 1)[1]
        ET.SubElement(actuator, 'position', name=name, joint=name,
                      kp=f'{c.KP[leg_joint]:g}', kv=f'{c.KD[leg_joint]:g}')

    sensor = ET.SubElement(root, 'sensor')
    ET.SubElement(sensor, 'gyro', name=c.GYRO_SENSOR, site=c.IMU_SITE)
    ET.SubElement(sensor, 'accelerometer', name=c.ACCELEROMETER_SENSOR, site=c.IMU_SITE)
    ET.SubElement(sensor, 'framequat', name=c.ORIENTATION_SENSOR, objtype='site',
                  objname=c.IMU_SITE)
    ET.SubElement(sensor, 'velocimeter', name=c.LOCAL_LINVEL_SENSOR, site=c.IMU_SITE)
    ET.SubElement(sensor, 'framelinvel', name=c.GLOBAL_LINVEL_SENSOR, objtype='site',
                  objname=c.IMU_SITE)
    for site, pos_name, vel_name, touch_name in zip(
            c.FOOT_SITES, c.FOOT_POS_SENSORS, c.FOOT_LINVEL_SENSORS, c.FOOT_TOUCH_SENSORS):
        ET.SubElement(sensor, 'framepos', name=pos_name, objtype='site', objname=site)
        ET.SubElement(sensor, 'framelinvel', name=vel_name, objtype='site', objname=site)
        ET.SubElement(sensor, 'touch', name=touch_name, site=f'{site}_touch')


def _home_qpos(xml: str):
    """Compute the home qpos: standing pose with the lowest sole corner just above the floor."""
    model = mujoco.MjModel.from_xml_string(xml)
    data = mujoco.MjData(model)
    qpos = model.qpos0.copy()
    for name, value in zip(c.JOINT_NAMES, c.STANDING_POSE):
        qpos[model.jnt_qposadr[model.joint(name).id]] = value
    data.qpos[:] = qpos
    mujoco.mj_kinematics(model, data)
    lowest = min(_lowest_corner(model, data, geom) for geom in c.FOOT_GEOMS)
    qpos[2] += HOME_CLEARANCE - lowest
    return qpos


def _lowest_corner(model, data, geom_name: str) -> float:
    geom = model.geom(geom_name).id
    half = model.geom_size[geom]
    rot = data.geom_xmat[geom].reshape(3, 3)
    corners = [data.geom_xpos[geom] + rot @ (half * (sx, sy, sz))
               for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]
    return min(corner[2] for corner in corners)


def build_xml(urdf: str) -> str:
    """Build the training MJCF from an expanded URDF."""
    root = urdf_to_mjcf(urdf)
    root.set('model', 'humanoid_rl')
    _add_world(root)
    _add_robot(root)
    xml = ET.tostring(root, encoding='unicode')
    qpos = _home_qpos(xml)
    keyframe = ET.SubElement(root, 'keyframe')
    ET.SubElement(keyframe, 'key', name=c.HOME_KEYFRAME, qpos=_fmt(qpos),
                  ctrl=_fmt(c.STANDING_POSE))
    root.insert(0, ET.Comment(HEADER))
    ET.indent(root, space='  ')
    return ET.tostring(root, encoding='unicode') + '\n'


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--xacro', default=XACRO_PATH, help='Description Xacro file.')
    parser.add_argument('--output', default=c.XML_PATH, help='Output MJCF file.')
    args = parser.parse_args(argv)
    xml = build_xml(expand_xacro(args.xacro))
    mujoco.MjModel.from_xml_string(xml)
    with open(args.output, 'w') as stream:
        stream.write(xml)
    print(f'Wrote {args.output}')


if __name__ == '__main__':
    main()
